/**
 * The app's legal documents, shown in-app by `LegalScreen`.
 *
 * In-app rather than a link because the pages used to live on the VPS, which is
 * being switched off — every link in the app would have died with it. The
 * public copies the stores record are sunray.sa's own pages (constants/legal.ts);
 * these say the same things, plus what only the app does (sign-in by SMS code,
 * the «وصلت» location check, where the data is hosted).
 *
 * Every statement here is checked against the code. Do not add a promise the
 * app does not keep — a policy that says more than the app does is the kind
 * store review rejects, and the kind a customer can hold us to.
 */

